%% sim11_broadcast_trajectories.m — Broadcast 3D: Multi-user trajectory estimation
%
% Flagship figure for the paper. Shows simultaneous 3D position estimation
% of N_users receivers following different trajectories, using only K
% broadcast measurements (no cooperative alignment).
%
% The figure demonstrates the practical broadcast capability:
%   - ONE LED scans K orientations
%   - Multiple receivers estimate their position SIMULTANEOUSLY
%   - Each uses NLS + broadcast_distance with known n_r
%
% Visual design:
%   - 3D perspective view of the room
%   - Ground truth trajectories as solid colored lines
%   - Estimated positions as markers (one per time step)
%   - LED at ceiling marked with star
%   - Room wireframe for context
%
% Author: Kevin Acuna-Condori
% Date: 27 May 2026
% Project: Proposal F — Broadcast OWP

close all; clear; clc;

%% Paths
addpath(fullfile(pwd, '..\core'));
addpath(fullfile(fileparts(pwd), '..', 'fundamentals', 'core'));

%% System Parameters
system_params_F;

% =========================================================================
% HYPERPARAMETERS
% =========================================================================
rng(7);
K_fixed      = 9;
M_avg        = 1;              % Single-shot per time step (realistic scenario)
N_users      = 4;              % Number of simultaneous receivers
N_steps      = 20;             % Time steps per trajectory
estimators   = {'NLS', 'GLS'}; % Which estimators to show
show_est     = 'NLS';          % Primary estimator for the main figure
SAVE_FIGS    = true;           % Save figures in IEEE format (png, pdf, eps)
% =========================================================================

%% Orientations
K_idx = find(K_values == K_fixed);
nt = orient_to_vectors(all_orientations_DEB{K_idx});
nt_rows = nt';

nr_col = n_r';  % [0;0;1]
param_r_ch = {A_det, n_r, FOV};

%% Define trajectories (3D paths within the room)
% Each trajectory: N_steps × 3 matrix [x, y, z]
% Design: diverse paths at different heights, crossing the room

%% Load trajectories (generated by generate_trajectories.m)
traj_file = fullfile(pwd, 'trajectories.mat');
if ~exist(traj_file, 'file')
    fprintf('Trajectories not found. Run generate_trajectories.m first.\n');
    fprintf('Running it now...\n');
    run(fullfile(pwd, 'generate_trajectories.m'));
end
S = load(traj_file);
trajectories = S.traj_true;
traj_colors  = S.colors;
traj_info    = S.traj_info;
N_users      = S.N_users;
N_steps      = S.N_steps;
fprintf('Loaded %d trajectories (%d steps each)\n', N_users, N_steps);

%% Simulate broadcast positioning for each user at each time step
estimates = cell(N_users, 1);  % N_steps × 3 per user
errors    = cell(N_users, 1);  % N_steps × 1

fprintf('Simulating %d users × %d steps (K=%d, broadcast)...\n', N_users, N_steps, K_fixed);

for iu = 1:N_users
    est_pos = zeros(N_steps, 3);
    err_pos = zeros(N_steps, 1);
    
    for it = 1:N_steps
        pos = trajectories{iu}(it, :);  % [x, y, z]
        x = pos(1); y = pos(2); z = pos(3);
        
        % Generate K channel powers
        P_clean = zeros(1, K_fixed);
        for id = 1:K_fixed
            pt = {T, nt_rows(id,:), P_t, m_t};
            [~, P_clean(id),~,~] = OWC_LOS_channel(x, y, z, pt, param_r_ch);
        end
        
        % Add noise
        P_raw = repmat(P_clean, N_samples, 1) + sqrt(sigma2).*randn(N_samples, K_fixed);
        mu_hat = mean(P_raw, 1);
        
        % Direction finding (selected estimator)
        switch show_est
            case 'NLS'
                nd_hat = vlp_nls_lm(nt, P_raw, m_t);
            case 'GLS'
                nd_hat = vlp_gls(nt, P_raw, m_t, sigma2);
        end
        [d_hat,~,~] = broadcast_distance(nd_hat, nt, mu_hat, m_t, C_opt, nr_col);
        
        est_pos(it,:) = T + (nd_hat' * d_hat);
        err_pos(it) = norm(pos - est_pos(it,:));
    end
    
    estimates{iu} = est_pos;
    errors{iu}    = err_pos;
    fprintf('  User %d: RMSE = %.2f cm, CDF90 = %.2f cm, APE = %.2f cm\n', ...
        iu, sqrt(mean(err_pos.^2))*100, prctile(err_pos*100, 90), mean(err_pos)*100);
end

%% ===== MAIN FIGURE: 3D Trajectory Estimation =====
fig = figure('Units','inches', 'Position',[0.5 0.5 7.16 5.5], 'Color', 'w');
ax = axes(fig);
hold(ax, 'on');

% --- Room wireframe ---
rx = [-L/2, L/2]; ry = [-W/2, W/2]; rz = [0, Hmax];
% Floor
plot3([rx(1) rx(2) rx(2) rx(1) rx(1)], [ry(1) ry(1) ry(2) ry(2) ry(1)], ...
      zeros(1,5), '-', 'Color', [0.7 0.7 0.7], 'LineWidth', 0.5, 'HandleVisibility','off');
% Ceiling at H=2 (transmitter level)
plot3([rx(1) rx(2) rx(2) rx(1) rx(1)], [ry(1) ry(1) ry(2) ry(2) ry(1)], ...
      2*ones(1,5), '-', 'Color', [0.85 0.85 0.85], 'LineWidth', 0.3, 'HandleVisibility','off');
% Vertical edges
for cx = rx
    for cy = ry
        plot3([cx cx], [cy cy], [0 2], '-', 'Color', [0.85 0.85 0.85], ...
            'LineWidth', 0.3, 'HandleVisibility','off');
    end
end





% --- Trajectories and estimates (inspired by standard positioning papers) ---
% Style: ground truth = solid line + circle markers at each position
%        estimated    = thin line + star/cross markers (overlaid on true)
% Similar to "Actual Position vs. Estimated Position" standard plots.

leg_h = gobjects(0); leg_l = {};

% Distinct marker styles per user for ground truth
gt_markers = {'o', 'd', '^'};    % circle, diamond, triangle-up
est_marker = '*';                 % star for all estimates (like reference image)

for iu = 1:N_users
    traj = trajectories{iu};
    est  = estimates{iu};
    col  = traj_colors(iu,:);
    col_est = min(col + 0.25, 0.95);  % Slightly lighter for estimates
    mk_gt = gt_markers{min(iu, length(gt_markers))};
    
    % Ground truth: line + markers at each position
    h_gt = plot3(traj(:,1), traj(:,2), traj(:,3), ['-' mk_gt], ...
        'LineWidth', 1.2, 'Color', col_est, ...
        'MarkerSize', 5, 'MarkerFaceColor', 'none', 'MarkerEdgeColor', col_est);
    
    % Estimated: line + star markers overlaid
    h_est = plot3(est(:,1), est(:,2), est(:,3), ['-' est_marker], ...
        'LineWidth', 0.8, 'Color', col, ...
        'MarkerSize', 5, 'MarkerEdgeColor', col);
    
    % Thin error segments connecting each pair (true ↔ estimated)
    for it = 1:3:N_steps  % Every 3rd point to avoid clutter
        plot3([traj(it,1) est(it,1)], [traj(it,2) est(it,2)], [traj(it,3) est(it,3)], ...
            '-', 'Color', [0.6 0.6 0.6 0.3], 'LineWidth', 0.3, 'HandleVisibility','off');
    end
    
    leg_h(end+1) = h_gt;
    leg_l{end+1} = sprintf('%s (true)', traj_info{iu}.type);
    leg_h(end+1) = h_est;
    leg_l{end+1} = sprintf('%s (est.)', traj_info{iu}.type);
end


% Draw K orientation vectors from LED position
vec_len = 0.30;  % Arrow length [m]
vec_col = [0.60 0.60 0.60];  % Medium gray
for io = 1:K_fixed
    v = nt(:, io);  % 3x1 unit vector
    quiver3(T(1), T(2), T(3), v(1)*vec_len, v(2)*vec_len, v(3)*vec_len, 0, ...
        'Color', vec_col, 'LineWidth', 1.3, 'MaxHeadSize', 0.6, ...
        'HandleVisibility', 'off');
end

% --- LED transmitter + orientation vectors ---
plot3(T(1), T(2), T(3), '.', 'MarkerSize', 15, 'Color', [0.3 0.3 0.3], ...
    'HandleVisibility', 'off');

% --- Formatting ---
xlabel('$x$ [m]', 'Interpreter','latex', 'FontSize', 12);
ylabel('$y$ [m]', 'Interpreter','latex', 'FontSize', 12);
zlabel('$z$ [m]', 'Interpreter','latex', 'FontSize', 12);

legend(leg_h, leg_l, 'Interpreter','latex', 'FontSize', 8, ...
    'Location','northeast', 'NumColumns', 1);

view(35, 25);
grid on; box on;
axis equal;
xlim([-L/2, L/2]); ylim([-W/2, W/2]); zlim([0, 2.1]);
set(ax, 'FontSize', 9, 'LineWidth', 0.6);

% Light and material for 3D feel
lighting gouraud;
camlight('headlight');

%% ===== FIGURE 2: Top-down XY view =====
fig2 = figure('Units','inches', 'Position',[0.5 0.5 3.5 3.2], 'Color', 'w');
hold on;

for iu = 1:N_users
    traj = trajectories{iu};
    est  = estimates{iu};
    col  = traj_colors(iu,:);
    col_est = min(col + 0.25, 0.95);
    mk_gt = gt_markers{min(iu, length(gt_markers))};
    
    plot(traj(:,1), traj(:,2), ['-' mk_gt], 'LineWidth', 1.2, 'Color', col_est, ...
        'MarkerSize', 5, 'MarkerFaceColor', 'none', 'MarkerEdgeColor', col_est);
    plot(est(:,1), est(:,2), ['-' est_marker], 'LineWidth', 0.8, 'Color', col, ...
        'MarkerSize', 5, 'MarkerEdgeColor', col);
end

% Room boundary
plot([-L/2 L/2 L/2 -L/2 -L/2], [-W/2 -W/2 W/2 W/2 -W/2], '-', ...
    'Color', [0.7 0.7 0.7], 'LineWidth', 0.8);
% LED position
plot(0, 0, '.', 'MarkerSize', 12, 'Color', [0.3 0.3 0.3]);

xlabel('$x$ [m]', 'Interpreter','latex', 'FontSize', 11);
ylabel('$y$ [m]', 'Interpreter','latex', 'FontSize', 11);
title(sprintf('Top View ($K{=}%d$, %s)', K_fixed, show_est), 'Interpreter','latex', 'FontSize', 12);
legend(cellfun(@(c) c.type, traj_info, 'UniformOutput', false), ...
    'Interpreter','latex', 'FontSize', 9, 'Location', 'northeast');
axis equal; grid on; box on;
xlim([-L/2 L/2]*1.05); ylim([-W/2 W/2]*1.05);
set(gca, 'FontSize', 9);

%% Save
results_dir = fullfile(pwd, 'results');
if ~exist(results_dir, 'dir'), mkdir(results_dir); end

if SAVE_FIGS
    % IEEE column width: 3.5 in (single) or 7.16 in (double)
    % Export at high resolution for print quality
    fig_name_3d = 'Fig_flagship_broadcast_3D';
    fig_name_xy = 'Fig_flagship_broadcast_XY';
    
    % Figure 1 (3D)
    exportgraphics(fig, fullfile(results_dir, [fig_name_3d '.pdf']), ...
        'ContentType','vector', 'BackgroundColor','white');
    exportgraphics(fig, fullfile(results_dir, [fig_name_3d '.png']), ...
        'Resolution', 600, 'BackgroundColor','white');
    exportgraphics(fig, fullfile(results_dir, [fig_name_3d '.eps']), ...
        'ContentType','vector', 'BackgroundColor','white');
    
    % Figure 2 (XY)
    exportgraphics(fig2, fullfile(results_dir, [fig_name_xy '.pdf']), ...
        'ContentType','vector', 'BackgroundColor','white');
    exportgraphics(fig2, fullfile(results_dir, [fig_name_xy '.png']), ...
        'Resolution', 600, 'BackgroundColor','white');
    exportgraphics(fig2, fullfile(results_dir, [fig_name_xy '.eps']), ...
        'ContentType','vector', 'BackgroundColor','white');
    
    fprintf('Figures saved (pdf/png/eps) to: %s\n', results_dir);
end

%% Print summary
all_err = cell2mat(cellfun(@(e) e*100, errors, 'UniformOutput', false));
fprintf('\n=== BROADCAST TRAJECTORY SUMMARY (K=%d, %s) ===\n', K_fixed, show_est);
fprintf('%-8s %10s %12s %10s\n', 'User', 'RMSE[cm]', 'CDF_90[cm]', 'APE[cm]');
for iu = 1:N_users
    e = errors{iu}*100;
    fprintf('%-8d %10.2f %12.2f %10.2f\n', iu, sqrt(mean(e.^2)), prctile(e, 90), mean(e));
end
fprintf('%-8s %10.2f %12.2f %10.2f\n', 'ALL', ...
    sqrt(mean(all_err.^2)), prctile(all_err, 90), mean(all_err));

fprintf('\nFigure saved.\n');
