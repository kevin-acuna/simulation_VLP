%% Fig_Time_IEEE  —  Computation Latency, K = 5  (GLS / WLS / NLS)
% Dot plot with p5–p95 interval on log scale.
% IEEE TCOM single-column format: 3.5 in × 2.6 in, 600 dpi.
%
% Data source: bench_*_DF_serial.m  (comparison_DF_best.txt)

close all; clear; clc;

% ── DATA  (K=5, serial benchmark, converted to ms) ────────────────────────
%                    GLS       WLS       NLS
med_v  = [0.02520,  0.01840,  0.6496];
mean_v = [0.02805,  0.02243,  0.7124];
p5_v   = [0.02430,  0.01730,  0.5303];
p95_v  = [0.04300,  0.04010,  1.11445];

lo = med_v - p5_v;
hi = p95_v - med_v;

x     = 1:3;
xlbls = {'GLS', 'WLS', 'NLS'};

% ── COLORS ────────────────────────────────────────────────────────────────
c_med  = [0.122, 0.471, 0.706];   % IEEE blue   — median marker
c_mean = [0.839, 0.153, 0.157];   % IEEE red    — mean marker
c_ci   = [0.122, 0.471, 0.706];   % same blue   — CI whisker

% ── FIGURE ────────────────────────────────────────────────────────────────
fig = figure('Units', 'inches', 'Position', [2 2 3.5 2.6], 'Color', 'w');

ax = axes('Parent', fig, ...
          'YScale',               'log',              ...
          'FontName',             'Times New Roman',  ...
          'FontSize',             8.5,                ...
          'TickDir',              'in',               ...
          'Box',                  'on',               ...
          'LineWidth',            0.8,                ...
          'TickLabelInterpreter', 'latex',            ...
          'XGrid',                'off',              ...
          'YGrid',                'on',               ...
          'YMinorGrid',           'on',               ...
          'GridLineStyle',        ':',                ...
          'GridAlpha',            0.30,               ...
          'MinorGridLineStyle',   ':',                ...
          'MinorGridAlpha',       0.10,               ...
          'TickLength',           [0.015 0.015]);
hold(ax, 'on');

% ── p5–p95 confidence interval ────────────────────────────────────────────
h_ci = errorbar(ax, x, med_v, lo, hi, ...
    'LineStyle', 'none', ...
    'Color',     c_ci,   ...
    'LineWidth', 1.10,   ...
    'CapSize',   6.5);

% ── Median  (filled circle) ───────────────────────────────────────────────
h_med = plot(ax, x, med_v, 'o', ...
    'MarkerSize',      3.5,  ...
    'MarkerFaceColor', c_med, ...
    'MarkerEdgeColor', 'k',  ...
    'LineWidth',       0.65);

% ── Mean  (filled diamond) ────────────────────────────────────────────────
h_mn = plot(ax, x, mean_v, 'd', ...
    'MarkerSize',      3.5,   ...
    'MarkerFaceColor', c_mean, ...
    'MarkerEdgeColor', 'k',   ...
    'LineWidth',       0.65);

% ── 1 ms reference line ───────────────────────────────────────────────────
yline(ax, 0.1, '--', ...
    'Color',                   [0.45 0.45 0.45], ...
    'LineWidth',               0.70,             ...
    'HandleVisibility',        'off',            ...
    'LabelHorizontalAlignment','left',           ...
    'LabelVerticalAlignment',  'bottom',         ...
    'FontSize',                7.0,              ...
    'FontName',                'Times New Roman');

% ── Median value annotations (right of each median dot) ──────────────────
x_off = [0.10, 0.10, 0.10];   % horizontal offset from dot centre
fmt   = {'$%.3f$~ms', '$%.3f$~ms', '$%.2f$~ms'};
for i = 1:3
    text(ax, x(i) + x_off(i), med_v(i), ...
        sprintf(fmt{i}, med_v(i)), ...
        'FontSize',            6.8,                ...
        'FontName',            'Times New Roman',  ...
        'HorizontalAlignment', 'left',             ...
        'VerticalAlignment',   'middle',           ...
        'Color',               [0.20 0.20 0.20],   ...
        'Interpreter',         'latex');
end

% ── AXES limits & ticks ───────────────────────────────────────────────────
xlim(ax, [0.45, 3.80]);
ylim(ax, [0.010, 5]);

set(ax, 'XTick', x, 'XTickLabel', xlbls, 'XTickLabelRotation', 0);
set(ax, 'YTick', [0.01, 0.1, 1, 10], ...
        'YTickLabel', {'0.01', '0.1', '1', '10'});

xlabel(ax, 'Direction-finding estimator', ...
       'FontSize', 9, 'FontName', 'Times New Roman', ...
       'Interpreter', 'latex');
ylabel(ax, 'Computation latency [ms]', ...
       'FontSize', 9, 'FontName', 'Times New Roman', ...
       'Interpreter', 'latex');

% ── LEGEND ────────────────────────────────────────────────────────────────
lgd = legend(ax, [h_ci, h_med, h_mn], ...
    {'90\% interval (p5--p95)', 'Median', 'Mean'}, ...
    'Interpreter',  'latex',            ...
    'Location',     'northwest',        ...
    'Box',          'on',               ...
    'FontSize',     7.5,                ...
    'FontName',     'Times New Roman');
lgd.ItemTokenSize = [13, 5];

% ── TIGHT LAYOUT ──────────────────────────────────────────────────────────
set(ax, 'Position', [0.155, 0.155, 0.815, 0.810]);

% ── EXPORT ────────────────────────────────────────────────────────────────
script_dir = fileparts(mfilename('fullpath'));
fig_dir = fullfile(script_dir, '..', '..', '..', ...
    'TCOM', 'Reviewed_submission', 'TCOM_paper', ...
    'Figures', 'VII.Simulations');

out_png = fullfile(fig_dir, 'Fig_Time.png');
out_pdf = fullfile(fig_dir, 'Fig_Time.pdf');

exportgraphics(fig, out_png, 'Resolution', 600, 'BackgroundColor', 'white');
exportgraphics(fig, out_pdf, 'ContentType', 'vector', 'BackgroundColor', 'white');
fprintf('PNG -> %s\n', out_png);
fprintf('PDF -> %s\n', out_pdf);