function fig = pp_figure(width_in, height_in)
% Invisible figure sized for IEEE (single column 3.5 in, double column 7.16 in), Times, 8 pt, light theme.
fig = figure('Visible', 'off', 'Color', 'w', 'Units', 'inches', 'Position', [1 1 width_in height_in], ...
    'PaperPositionMode', 'auto');
try
    fig.Theme = 'light';
catch
end
set(fig, 'DefaultAxesFontName', 'Times New Roman', 'DefaultAxesFontSize', 8, ...
    'DefaultTextFontName', 'Times New Roman', 'DefaultTextFontSize', 8, ...
    'DefaultLegendFontName', 'Times New Roman', 'DefaultLegendFontSize', 7, ...
    'DefaultAxesLineWidth', 0.5, 'DefaultLineLineWidth', 1.0, 'DefaultAxesBox', 'on', ...
    'DefaultAxesTickDir', 'in', 'DefaultAxesXGrid', 'on', 'DefaultAxesYGrid', 'on', ...
    'DefaultAxesGridAlpha', 0.15, 'DefaultAxesTickLabelInterpreter', 'latex', ...
    'DefaultTextInterpreter', 'latex', 'DefaultLegendInterpreter', 'latex', ...
    'DefaultColorbarTickLabelInterpreter', 'latex');
end
